import assert from 'node:assert/strict';
import { execFileSync, execFile } from 'node:child_process';
import { promisify } from 'node:util';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright-core');
const php = process.env.VECTOR_BROWSER_PHP || 'php';
const api = process.env.VECTOR_BROWSER_API_URL || 'http://127.0.0.1:8000';
const base = process.env.VECTOR_BROWSER_BASE_URL || 'http://127.0.0.1:4173';
const snapshot = () => execFileSync(php, ['scripts/browser/historical_fixture.php', 'snapshot'], { encoding: 'utf8' }).trim();
const before = snapshot();
const browser = await chromium.launch({ executablePath: '/usr/bin/google-chrome', headless: true, args: ['--no-sandbox'] });
const page = await browser.newPage({ viewport: { width: 1500, height: 1600 } });
page.setDefaultTimeout(30000);
const errors = []; page.on('pageerror', e => errors.push(e.message));
const button = name => page.getByRole('button', { name, exact: true });
const response = (end, method = 'POST') => page.waitForResponse(r => r.url().includes('/historical/') && r.url().endsWith(end) && r.request().method() === method, { timeout: 45000 });
const accept = async p => { const r = await p; assert.ok(r.ok(), `${r.status()} ${await r.text()}`); return (await r.json()).data; };
const click = async (name, suffix, method = 'POST') => { console.log('STEP', name); const p = response(suffix, method); await button(name).click(); return accept(p); };
try {
  await page.route('**/api/**', async route => { const url = new URL(route.request().url()); url.host = new URL(api).host; const r = await route.fetch({ url: url.toString(), timeout: 180000 }); await route.fulfill({ response: r }); });
  await page.goto(`${base}/exchanges/binance/historical`);
  await page.getByLabel('Research owner token', { exact: true }).fill('vision-browser-test');
  await click('Load batches', '/batches?page=1', 'GET');
  const preset = await click('Preview download plan', '/preview');
  assert.equal(preset.estimate.candle_archives, 240); assert.equal(preset.estimate.expected_candles, 2771952);
  const cancelled = await click('Save plan without downloading', '/batches');
  assert.equal(cancelled.status, 'PLANNED');
  assert.equal(await button('Start / resume downloads').isDisabled(), true);
  await click('Cancel batch', '/cancel');
  await page.getByLabel('Instruments', { exact: true }).click();
  await page.getByRole('option', { name: 'ETHUSDT', exact: true }).click(); await page.keyboard.press('Escape');
  await page.getByLabel('Intervals', { exact: true }).click();
  await page.getByRole('option', { name: '1m', exact: true }).click(); await page.keyboard.press('Escape');
  await page.getByLabel('Start UTC', { exact: true }).fill('2024-01-01T00:00:00Z');
  await page.getByLabel('Inclusive end UTC (.999)', { exact: true }).fill('2024-01-15T00:59:59.999Z');
  const plan = await click('Preview download plan', '/preview'); assert.equal(plan.estimate.candle_archives, 4);
  const batch = await click('Save plan without downloading', '/batches');
  await page.getByLabel('I acknowledge the recorded Binance terms for permitted non-commercial research and the resource estimate.', { exact: true }).check();
  await page.getByLabel('Owner acknowledgement reference (8–160 characters)', { exact: true }).fill('BROWSER-OWNER-ACK');
  await click('Start / resume downloads', '/start');
  await click('Pause downloads', '/pause');
  await click('Start / resume downloads', '/resume');
  const worker = promisify(execFile);
  await worker(php, ['scripts/browser/historical_fixture.php', 'work'], { timeout: 100000 });
  await click('Refresh progress', `/batches/${batch.id}`, 'GET');
  const quality = await click('Validate imported coverage', '/validate');
  assert.equal(quality.status, 'VALIDATED'); assert.equal(quality.funding_complete, true); assert.equal(quality.research_ready, true);
  const stratSelect = page.getByLabel('Strategy / immutable version', { exact: true });
  await stratSelect.evaluate(el => el.scrollIntoView({ block: 'center' }));
  await stratSelect.click();
  const option = page.getByRole('option', { name: 'user_vision_browser v1 · DSL', exact: true });
  await option.evaluate(el => el.click());
  await page.getByLabel('Replay start UTC (warmup required)', { exact: true }).fill('2024-01-12T00:00:00Z');
  await page.getByLabel('Replay end UTC (exclusive)', { exact: true }).fill('2024-01-14T00:00:00Z');
  const run = await click('Run Historical Backtest', '/research'); assert.equal(run.status, 'QUEUED');
  await worker(php, ['scripts/browser/historical_fixture.php', 'work'], { timeout: 100000 });
  await click('Refresh progress', `/batches/${batch.id}`, 'GET');
  await page.getByTestId('history-run').getByText('Historical research · COMPLETED', { exact: true }).waitFor({ timeout: 30000 });
  const final = await page.request.get(`${api}/api/v1/historical/runs/${run.id}`, { headers: { 'X-Research-Token': 'vision-browser-test' } });
  const result = await accept(Promise.resolve(final));
  assert.ok(result.result.report.total_trades > 0);
  assert.equal(snapshot(), before); assert.match(before, /\|26\|26$/);
  assert.deepEqual(errors, []);
  await page.screenshot({ path: process.env.VECTOR_BROWSER_SCREENSHOT || '/tmp/vector-vision-browser.png', fullPage: true });
  console.log(JSON.stringify({ status: 'PASS', batch: batch.id, run: run.id, pin: result.dataset_pin, trades: result.result.report.total_trades, coverage: quality, paper_before_after: before, page_errors: errors, fixed_synthetic_fixture: true }));
} catch (error) { console.log('BODY', (await page.locator('body').innerText()).slice(0,4000)); await page.screenshot({ path: '/tmp/vector-vision-browser-failed.png', fullPage: true }); throw error; } finally { await page.unrouteAll({ behavior: 'ignoreErrors' }); await browser.close(); }
