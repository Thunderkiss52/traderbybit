    /** @var array<string, TradingMethodDefinition> */
    private array $methods = [];

    public function __construct()
    {
        $this->registerCatalog();
    }

    /** @return list<TradingMethodDefinition> */
    public function all(): array
    {
        return array_values($this->methods);
    }

    public function find(string $id): ?TradingMethodDefinition
    {
        return $this->methods[$id] ?? null;
    }

    public function get(string $id): TradingMethodDefinition
    {
        return $this->find($id) ?? throw new InvalidArgumentException("Unknown trading method: '{$id}'.");
    }

    /** @return list<TradingMethodDefinition> */
    public function filter(?MethodCategory $category = null, ?MethodType $type = null, ?MethodImplementationStatus $status = null): array
    {
        return array_values(array_filter($this->methods, static function (TradingMethodDefinition $m) use ($category, $type, $status): bool {
            if ($category !== null && $m->category !== $category) {
                return false;
            }
            if ($type !== null && $m->type !== $type) {
                return false;
            }
            if ($status !== null && $m->status !== $status) {
                return false;
            }

            return true;
        }));
    }

